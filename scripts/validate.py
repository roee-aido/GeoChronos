"""GeoChronos validation suite: GEO-First, TIME-First, POV-First, combined, provenance and time representation.

Runs against build/geochronos.sqlite (build it first with scripts/build_db.py),
asserts expected results that were fixed BEFORE running (from the curated seed),
and writes build/validation_report.md with every result table.

Usage:  python scripts/validate.py [--db build/geochronos_base.sqlite] [--report build/validation_report.md]
The fixed expectations below were written for the BASE seed (57 Items). Run them against the base
profile build; the expansion is validated separately (scripts/validate_expansion.py).
"""
import argparse
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import geoquery as gq  # noqa: E402
import timefmt as tf  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
REPORT = ROOT / "build" / "validation_report.md"

I = lambda *names: {f"item:{n}" for n in names}  # noqa: E731


class Suite:
    def __init__(self, con):
        self.con, self.results, self.md = con, [], []

    def check(self, name, rows, must_include=(), must_exclude=(), exact=None, note=None, columns=None):
        ids = {r["entity_id"] for r in rows}
        problems = []
        if exact is not None and ids != set(exact):
            problems.append(f"expected exactly {sorted(exact)}; missing {sorted(set(exact) - ids)}, unexpected {sorted(ids - set(exact))}")
        missing = set(must_include) - ids
        if missing:
            problems.append(f"missing {sorted(missing)}")
        wrong = set(must_exclude) & ids
        if wrong:
            problems.append(f"should not contain {sorted(wrong)}")
        ok = not problems
        self.results.append((name, ok, problems))
        self.md += [f"### {'PASS' if ok else 'FAIL'} — {name}", ""]
        if note:
            self.md += [f"_{note}_", ""]
        for p in problems:
            self.md.append(f"- **{p}**")
        cols = columns or ["canonical_name"]
        self.md += [f"{len(rows)} result(s)", "", "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
        for r in rows:
            self.md.append("| " + " | ".join("" if r.get(c) is None else str(r.get(c)) for c in cols) + " |")
        self.md.append("")
        return rows

    def assert_true(self, name, cond, detail=""):
        self.results.append((name, bool(cond), [] if cond else [detail]))
        self.md += [f"### {'PASS' if cond else 'FAIL'} — {name}", "", detail, ""]


def run(db=None, report=None):
    global REPORT
    if report:
        REPORT = pathlib.Path(report)
    con = gq.connect(db or gq.BASE_DB_PATH)
    s = Suite(con)
    TCOLS = ["canonical_name", "role", "civil", "bp", "hebrew", "rank", "status", "matching_claims", "open_ended"]

    s.md += ["# GeoChronos validation report", "", f"Generated by `scripts/validate.py` from `{pathlib.Path(db or gq.BASE_DB_PATH).name}`.", ""]

    # ------------------------------------------------------------ GEO ----
    s.md += ["## GEO-First", ""]
    s.check("Items in Egypt (modern country, via place graph)", gq.geo_in_place(con, "place:country:egypt"),
            must_include=I("great-pyramid-of-giza", "pyramid-of-djoser", "great-sphinx-of-giza", "tomb-of-tutankhamun-kv62",
                           "karnak-temple-complex", "abu-simbel-temples", "rosetta-stone", "mask-of-tutankhamun"),
            must_exclude=I("pyramids-of-meroe"), note="Meroë is in Sudan: must not appear although it has pyramids.")
    s.check("Items in Europe (continent)", gq.geo_in_place(con, "place:continent:europe"),
            must_include=I("stonehenge", "newgrange", "carnac-stones", "hagar-qim", "dolmen-of-menga", "skara-brae",
                           "lascaux-cave", "knossos", "parthenon", "colosseum", "pompeii", "venus-of-willendorf"),
            must_exclude=I("gobekli-tepe", "catalhoyuk"),
            note="Turkey is transcontinental ('overlaps' Europe and Asia); Anatolian sites must resolve to Asia only.")
    s.check("Items in Asia (continent)", gq.geo_in_place(con, "place:continent:asia"),
            must_include=I("gobekli-tepe", "catalhoyuk", "mohenjo-daro", "angkor-wat", "masada", "qumran-caves"))
    s.check("Items in Mesoamerica (historical region)", gq.geo_in_place(con, "place:region:mesoamerica"),
            must_include=I("teotihuacan", "pyramid-of-the-sun", "chichen-itza", "temple-of-kukulcan", "tikal"))
    s.check("Items in the Levant (historical region)", gq.geo_in_place(con, "place:region:levant"),
            must_include=I("masada", "qumran-caves", "dead-sea-scrolls", "tell-es-sultan", "tower-of-jericho", "petra"))
    s.check("Within 20 km of the Great Pyramid (radius)", gq.geo_near(con, 29.97915, 31.13422, 20),
            must_include=I("great-pyramid-of-giza", "great-sphinx-of-giza", "pyramid-of-djoser"),
            columns=["canonical_name", "km"])
    s.check("Aegean bounding box (lat 34.5–38.5, lon 22–27)", gq.geo_bbox(con, 34.5, 22.0, 38.5, 27.0),
            must_include=I("knossos", "akrotiri", "parthenon", "treasury-of-atreus", "antikythera-mechanism"),
            columns=["canonical_name", "lat", "lon", "via"])
    s.check("Sub-structure inherits location (Tower of Jericho, via part_of)",
            gq.geo_near(con, 31.87171944, 35.44456389, 1), must_include=I("tower-of-jericho", "tell-es-sultan"),
            columns=["canonical_name", "km"])
    s.check("Objects currently held in London (current keeper, not find spot)",
            gq.geo_currently_held_in(con, "place:city:london"), must_include=I("rosetta-stone"),
            columns=["canonical_name", "keeper"])

    # ----------------------------------------------------------- TIME ----
    s.md += ["## TIME-First", ""]
    s.check("What existed around 2500 BCE ± 500 (3000–2000 BCE), possible overlap", gq.time_overlap(con, -3000, -2000),
            must_include=I("great-pyramid-of-giza", "pyramid-of-djoser", "great-sphinx-of-giza", "stonehenge", "newgrange",
                           "skara-brae", "mohenjo-daro", "caral", "ziggurat-of-ur"),
            must_exclude=I("tomb-of-tutankhamun-kv62", "parthenon", "gobekli-tepe", "hagar-qim"), columns=TCOLS)
    s.check("Same window, unknown ends read as unbounded (opt-in)", gq.time_overlap(con, -3000, -2000, open_end="unbounded"),
            must_include=I("gobekli-tepe", "great-pyramid-of-giza"), columns=TCOLS,
            note="Göbekli Tepe ('inhabited … to at least 8000 BCE') appears only when unknown ends are treated as unbounded; flagged open_ended.")
    s.check("Same window, CERTAIN overlap only", gq.time_overlap(con, -3000, -2000, mode="certain"),
            must_include=I("great-pyramid-of-giza", "skara-brae", "mohenjo-daro"), columns=TCOLS,
            note="'certain' requires the uncertain range to overlap no matter where the true dates fall.")
    s.check("Deep time: 100,000–60,000 years ago", gq.time_overlap(con, 1950 - 100000, 1950 - 60000),
            must_include=I("blombos-cave"), columns=TCOLS)
    s.check("Snapshot: the year 79 CE", gq.time_overlap(con, 79, 79),
            must_include=I("pompeii", "colosseum", "dead-sea-scrolls", "teotihuacan"), columns=TCOLS)
    s.check("Heritage-history layer: discoveries 1900–1950 (role filter)",
            gq.time_overlap(con, 1900, 1950, roles=("discovery",)),
            must_include=I("tomb-of-tutankhamun-kv62", "lascaux-cave", "sutton-hoo", "venus-of-willendorf", "antikythera-mechanism"),
            columns=TCOLS)

    # ------------------------------------------------------------ POV ----
    s.md += ["## POV-First", ""]
    s.check("Show pyramids (form: pyramid, incl. narrower)", gq.pov(con, "concept:form:pyramid"),
            must_include=I("great-pyramid-of-giza", "pyramid-of-djoser", "pyramids-of-meroe", "pyramid-of-the-sun",
                           "temple-of-kukulcan", "caral"),
            must_exclude=I("ziggurat-of-ur", "monks-mound"), columns=["canonical_name", "via"])
    s.check("Show pyramidal structures (umbrella incl. ziggurats, platform mounds)", gq.pov(con, "concept:form:pyramidal-structure"),
            must_include=I("great-pyramid-of-giza", "ziggurat-of-ur", "monks-mound", "cahokia"), columns=["canonical_name", "via"])
    s.check("Show Egyptian items (culture)", gq.pov(con, "culture:ancient-egypt"),
            must_include=I("great-pyramid-of-giza", "pyramid-of-djoser", "great-sphinx-of-giza", "tomb-of-tutankhamun-kv62",
                           "karnak-temple-complex", "abu-simbel-temples", "rosetta-stone", "mask-of-tutankhamun"),
            must_exclude=I("pyramids-of-meroe"), columns=["canonical_name", "via"])
    s.check("Show tombs (function: tomb)", gq.pov(con, "concept:function:tomb"),
            must_include=I("great-pyramid-of-giza", "pyramid-of-djoser", "tomb-of-tutankhamun-kv62", "pyramids-of-meroe",
                           "newgrange", "dolmen-of-menga", "treasury-of-atreus", "sutton-hoo", "mausoleum-of-qin-shi-huang",
                           "gochang-hwasun-ganghwa-dolmens"),
            must_exclude=I("stonehenge", "great-sphinx-of-giza"), columns=["canonical_name", "via", "has_uncertain_link"],
            note="Stonehenge has function 'funerary' (broader than tomb) and must not appear under 'tomb'.")
    s.check("Show megalithic sites (form: megalith, incl. narrower)", gq.pov(con, "concept:form:megalith"),
            must_include=I("stonehenge", "newgrange", "carnac-stones", "hagar-qim", "dolmen-of-menga", "gobekli-tepe",
                           "gochang-hwasun-ganghwa-dolmens", "nan-madol"), columns=["canonical_name", "via"])
    s.check("Everything linked to Khufu (person as point of view)",
            [dict(r, entity_id=r["entity_id"]) for r in gq.pov_related_to(con, "person:khufu")],
            must_include=I("great-pyramid-of-giza", "great-sphinx-of-giza"),
            columns=["canonical_name", "predicate_id", "status", "dispute_group"])
    s.check("Religion POV: Judaism (incl. Wikidata-imported links)", gq.pov(con, "religion:judaism"),
            must_include=I("dead-sea-scrolls"), columns=["canonical_name", "via"])

    # ------------------------------------------------------- combined ----
    s.md += ["## Combined (GEO × TIME × POV)", ""]
    s.check("Egypt + Tomb + 3000–2000 BCE",
            gq.combined(con, place_id="place:country:egypt", concept_id="concept:function:tomb", time_range=(-3000, -2000)),
            exact=I("great-pyramid-of-giza", "pyramid-of-djoser"), columns=["canonical_name", "civil", "status"])
    s.check("Megalithic + Europe + 5000–2000 BCE",
            gq.combined(con, place_id="place:continent:europe", concept_id="concept:form:megalith", time_range=(-5000, -2000)),
            exact=I("stonehenge", "newgrange", "carnac-stones", "hagar-qim", "dolmen-of-menga"),
            columns=["canonical_name", "civil", "status"])
    s.check("Pyramids + Americas-wide (North America) + 1st millennium CE",
            gq.combined(con, place_id="place:continent:north-america", concept_id="concept:form:pyramidal-structure", time_range=(1, 1000)),
            must_include=I("pyramid-of-the-sun", "temple-of-kukulcan", "monks-mound"), columns=["canonical_name", "civil", "status"])

    # ----------------------------------------------------- provenance ----
    s.md += ["## Provenance & uncertainty", ""]
    sph = gq.dispute(con, "sphinx:attribution")
    s.assert_true("Great Sphinx attribution keeps BOTH claims, neither preferred",
                  len(sph) == 2 and all(r["status"] == "disputed" for r in sph) and not any(r["rank"] == "preferred" for r in sph),
                  f"{[(r['object_id'], r['status'], r['rank']) for r in sph]}")
    ves = gq.dispute(con, "vesuvius-79:date")
    s.assert_true("Vesuvius 79 date: ≥3 competing day-level claims retained", len(ves) >= 3,
                  "; ".join(f"{r['temporal_label']} [{r['status']}/{r['rank']}] -> {tf.format_civil(r)} | {tf.format_hebrew(r)}" for r in ves))
    thera = gq.dispute(con, "thera:date")
    s.assert_true("Thera eruption: radiocarbon vs archaeological dating both kept (event + Akrotiri)", len(thera) >= 4,
                  "; ".join(f"{r['entity_id']}: {r['temporal_label']}" for r in thera))
    no_ev = con.execute("SELECT COUNT(*) FROM claim WHERE claim_id NOT IN (SELECT claim_id FROM claim_evidence)").fetchone()[0]
    s.assert_true("Every claim has at least one evidence row", no_ev == 0, f"{no_ev} claims without evidence")
    ed = con.execute("""SELECT COUNT(*) FROM claim c WHERE c.statement_type IN ('temporal','location') AND NOT EXISTS
                        (SELECT 1 FROM claim_evidence e WHERE e.claim_id=c.claim_id AND e.source_id<>'src:gc-editorial')""").fetchone()[0]
    s.assert_true("No date or coordinate rests only on editorial curation", ed == 0, f"{ed} editorial-only date/coordinate claims")
    corr = con.execute("""SELECT COUNT(*) FROM claim c WHERE
                          EXISTS (SELECT 1 FROM claim_evidence e WHERE e.claim_id=c.claim_id AND e.source_id='src:wikidata') AND
                          EXISTS (SELECT 1 FROM claim_evidence e WHERE e.claim_id=c.claim_id AND e.source_id='src:wikipedia-en')""").fetchone()[0]
    s.assert_true("Curated claims corroborated by Wikidata carry both sources", corr > 0, f"{corr} claims with 2 independent sources")
    laly = [r for r in gq.claims_for(con, "item:rock-hewn-churches-lalibela", "relation") if r["status"] == "disputed"]
    s.assert_true("Questionable Wikidata link kept as 'disputed', not deleted (Lalibela / Eastern Orthodoxy)", len(laly) >= 1,
                  f"{len(laly)} disputed relation claim(s)")
    ang = con.execute("""SELECT t.label, c.status FROM temporal_extent t JOIN claim c ON c.claim_id=t.claim_id
                         WHERE t.entity_id='item:angkor-wat' AND t.earliest_start <= 802 AND t.latest_end >= 802""").fetchall()
    s.assert_true("Suspicious Wikidata inception (Angkor Wat 802) imported but flagged disputed",
                  ang and all(r[1] == "disputed" for r in ang), f"{[tuple(r) for r in ang]}")

    # ------------------------------------------------ representations ----
    s.md += ["## One value, many representations", ""]
    ros = con.execute("""SELECT t.* FROM temporal_extent t JOIN claim c ON c.claim_id=t.claim_id
                         WHERE t.entity_id='item:rosetta-stone' AND t.role='creation' AND c.rank='preferred'""").fetchone()
    ros = dict(ros)
    s.assert_true("Rosetta Stone decree: day-precise JDN stored once, rendered in several calendars",
                  ros["jdn_start"] == tf.jdn_from_date(-195, 3, 27, "julian"),
                  f"stored: astro year {ros['earliest_start']}, JDN {ros['jdn_start']} → civil: {tf.format_civil(ros)} · "
                  f"BP: {tf.format_bp(ros)} · Hebrew: {tf.format_hebrew(ros)} · עברית: {tf.format_hebrew(ros, 'he')}")
    gp = dict(con.execute("""SELECT t.* FROM temporal_extent t JOIN claim c ON c.claim_id=t.claim_id
                             WHERE t.entity_id='item:great-pyramid-of-giza' AND c.rank='preferred'""").fetchone())
    s.assert_true("Great Pyramid preferred range rendered as CE/BCE, BP and Anno Mundi",
                  tf.format_civil(gp).endswith("BCE"),
                  f"{tf.format_civil(gp)} · {tf.format_bp(gp)} · {tf.format_hebrew(gp)} · {tf.format_hebrew(gp, 'he')}")
    gt = dict(con.execute("SELECT * FROM temporal_extent WHERE entity_id='item:gobekli-tepe' AND role='occupation'").fetchone())
    s.assert_true("Before the Anno Mundi epoch the Hebrew formatter says so explicitly (Göbekli Tepe)",
                  "before AM 1" in tf.format_hebrew(gt), f"{tf.format_civil(gt)} → {tf.format_hebrew(gt)}")
    s.assert_true("Calendar arithmetic self-test (Hebrew/Julian/Gregorian anchors)", tf.self_test(), "timefmt.self_test()")

    # ---------------------------------------------------------- output ---
    passed = sum(ok for _, ok, _ in s.results)
    head = ["", f"**{passed}/{len(s.results)} checks passed.**", ""]
    s.md[4:4] = head
    REPORT.write_text("\n".join(s.md) + "\n", encoding="utf-8")
    for name, ok, problems in s.results:
        print(f"[{'PASS' if ok else 'FAIL'}] {name}" + ("" if ok else f"  -> {problems}"))
    print(f"\n{passed}/{len(s.results)} checks passed. Report: {REPORT}")
    return passed == len(s.results)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--db")
    ap.add_argument("--report")
    a = ap.parse_args()
    sys.exit(0 if run(a.db, a.report) else 1)
